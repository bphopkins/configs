# 00-shell-opts.sh
# Shell behavior settings (shopt, set)
#
# This file configures how bash itself behaves: history handling,
# globbing, job control, error handling, etc. These settings affect
# how subsequent configuration is parsed and how the shell responds
# to your input.
#
# Intentionally empty for now -- kept as the reserved slot so that when a
# shopt/set option is wanted there is no question about where it goes, and it
# lands before anything else in ~/.bashrc.d parses. Same for 30-prompt.sh.
